/**
 * 명리 용어 기반 문장을 친근하고 동화 같은 어린이용 해석으로 다이내믹하게 변환합니다.
 */
export function translateToFriendlyTone(text: string, myName: string, otherName: string): string {
  if (!text) return "";

  const my = myName || "나";
  const other = otherName || "상대";

  // 1. 단락 수준의 맵핑 우선 적용 (가장 어울리는 비유 제시)
  for (const m of PARAGRAPH_MAPPINGS) {
    if (m.keywords.some(k => text.includes(k))) {
      return m.friendly;
    }
  }

  // 2. 문장을 어투 변환 및 단어 치환
  let friendlyText = text;

  // 단어 치환 진행
  for (const [regex, replacement] of WORD_REPLACEMENTS) {
    friendlyText = friendlyText.replace(regex, replacement);
  }

  // 어투 치환: "~합니다", "~임", "~이다" 등 딱딱한 서술어를 부드러운 구어체로 변경
  friendlyText = friendlyText
    .replace(/합니다\./g, "해요! ✨")
    .replace(/됩니다\./g, "된답니다. 🎈")
    .replace(/있습니다\./g, "있어요. 🧸")
    .replace(/없습니다\./g, "없답니다. 💧")
    .replace(/않습니다\./g, "않아요. 🌸")
    .replace(/필요합니다\./g, "도움이 돼요. 🌱")
    .replace(/주의하세요\./g, "한 번 더 안아주며 토닥토닥해 주세요. 💕")
    .replace(/권장합니다\./g, "해보는 건 어떨까요? 😉")
    .replace(/나타납니다\./g, "드러나요. 🌟")
    .replace(/작용합니다\./g, "찾아와요. 🍀")
    .replace(/발생할 수 있습니다/g, "생기기도 해요")
    .replace(/어려울 수 있습니다/g, "조금 속상할 수 있어요")
    .replace(/유리합니다\./g, "참 좋답니다. 👍")
    .replace(/안정적입니다\./g, "마음이 편안해져요. 🏡")
    .replace(/충돌합니다\./g, "서로 토라져요. ⚡")
    .replace(/마찰이 발생합니다/g, "티격태격하기도 해요")
    .replace(/요구됩니다\./g, "필요해요. 🌻")
    .replace(/강화합니다\./g, "더 튼튼하게 만들어 줘요. 💪");

  // 이름 변환 적용
  friendlyText = friendlyText
    .replace(/person1|Person1/g, my)
    .replace(/person2|Person2/g, other)
    .replace(/두 사람/g, `${my}와 ${other}`);

  return friendlyText;
}
